// The UI test renders through the same Miuix theme as the app and additionally asserts that the
// phase-1 native bridge loads in a plain JVM — so it needs the same lyrico.native.dir the app gets.
tasks.named<Test>("test") {
    val nativeDir = rootProject.layout.projectDirectory.dir("build/native/windows-x64").asFile.absolutePath
    systemProperty("lyrico.native.dir", nativeDir)
    // Where SchemaFidelityTest compares the generated desktop schema against the inherited one.
    systemProperty("lyrico.schema.dir", layout.projectDirectory.dir("schemas").asFile.absolutePath)
    systemProperty(
        "lyrico.android.schema.dir",
        layout.projectDirectory.dir("schemas-android").asFile.absolutePath,
    )
    // TagLib's vendored test audio files, used as tag read/write fixtures.
    systemProperty(
        "lyrico.audiotag.fixtures.dir",
        rootProject.layout.projectDirectory
            .dir("lyrico-audiotag/src/main/cpp/taglib/tests/data")
            .asFile.absolutePath,
    )
    // `DevLibrarySeederTest` rewrites the app's own data folder, so it only runs when asked for:
    //   ./gradlew :lyrico-app:test --tests "*DevLibrarySeederTest*" -Plyrico.seedDevLibrary=1
    // A project property rather than an environment variable, because the Gradle daemon (not the
    // calling shell) hands the environment to the test worker.
    systemProperty("lyrico.seedDevLibrary", providers.gradleProperty("lyrico.seedDevLibrary").getOrElse("0"))
    // `DevPluginSeederTest` installs a demo plugin into the app's own data folder for the same
    // reason, and is gated the same way:
    //   ./gradlew :lyrico-app:test --tests "*DevPluginSeederTest*" -Plyrico.seedDevPlugin=1
    systemProperty("lyrico.seedDevPlugin", providers.gradleProperty("lyrico.seedDevPlugin").getOrElse("0"))
}

compose.desktop {
    application {
        mainClass = "com.lonx.lyrico.MainKt"

        // Native libraries are built by scripts/build-native.ps1 (phase 1) and shipped next to the
        // app; the loader resolves them through the lyrico.native.dir system property, defaulting to
        // the per-OS directory under build/native.
        val nativeDir = rootProject.layout.projectDirectory.dir("build/native/windows-x64").asFile.absolutePath
        jvmArgs += listOf("-Dlyrico.native.dir=$nativeDir", "-Dlyrico.version=$version")

        // The dev start-route override (`Main` -> `LyricoNavHost` -> `desktopStartDestination`) exists so
        // a screen with no in-app entry point yet can still be captured in the real window. Gradle's own
        // `-D` flags land on the daemon, not on the app, so the value is forwarded here:
        //   ./gradlew :lyrico-app:run -Plyrico.start.route=plugin_manager
        providers.gradleProperty("lyrico.start.route").orNull?.takeIf { it.isNotBlank() }?.let { route ->
            jvmArgs += listOf("-Dlyrico.start.route=$route")
        }

        nativeDistributions {
            targetFormats(TargetFormat.Msi, TargetFormat.Exe)
            packageName = "Lyrico"
            // Placeholder until the packaging phase (PLAN.md phase 6) — jpackage rejects a version
            // with a suffix, and Windows wants x.y.z.w with the major >= 1.
            packageVersion = baseVersionName
            description = "Lyrico — audio tag editor"
            vendor = "Lonx"

            windows {
                menu = true
                shortcut = true
                // File association (.mp3/.flac/...) and per-user vs per-machine install scope are
                // decided in phase 6.
                dirChooser = true
            }

            modules("java.naming", "java.sql", "jdk.unsupported", "java.desktop")
        }
    }
}
