 * version catalog.
 *
 * The page used to hard-code them (and drifted: six were wrong when it was first written). The half that
 * Gradle knows about is now generated; the vendored sidecars (TagLib, libebur128, quickjs-ng, the ffmpeg
 * binary) are still hand-written, because no Gradle metadata describes them -- their versions come from the
 * upstream headers and `docs/third-party/ffmpeg-lgpl.md`, and `AppLicencesTest` keeps them non-empty.
 */
val generateLicenceVersions = tasks.register("generateLicenceVersions") {
    val outputDir = layout.buildDirectory.dir("generated/licences")
    val versions = mapOf(
        "COMPOSE_MULTIPLATFORM" to libs.versions.composeMultiplatform.get(),
        "MIUIX" to libs.versions.miuix.get(),
        "KOIN" to libs.versions.koin.get(),
        "COROUTINES" to libs.versions.coroutines.get(),
        "SERIALIZATION" to libs.versions.kotlinxSerializationJson.get(),
        "ROOM" to libs.versions.room.get(),
        "DATASTORE" to libs.versions.datastorePreferences.get(),
        "OKHTTP" to libs.versions.okhttp.get(),
        "COIL" to libs.versions.coil.get(),
        "MULTIPLATFORM_MARKDOWN" to libs.versions.multiplatformMarkdown.get(),
    )
    inputs.property("versions", versions)
    outputs.dir(outputDir)
    doLast {
        val dir = outputDir.get().asFile.resolve("com/lonx/lyrico/data/model")
        dir.mkdirs()
        dir.resolve("LicenceVersions.kt").writeText(
            buildString {
                appendLine("// Generated by the :lyrico-app build from gradle/libs.versions.toml — do not edit.")
                appendLine("package com.lonx.lyrico.data.model")
                appendLine()
                appendLine("object LicenceVersions {")
                for ((name, value) in versions) {
                    appendLine("    const val $name: String = \"$value\"")
                }
                appendLine("}")
            },
        )
    }
}

